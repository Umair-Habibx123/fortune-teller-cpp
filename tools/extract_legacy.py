#!/usr/bin/env python3
"""Extract the original texts from legacy/ into src/LegacyData.cpp.

The modern app reuses every piece of writing from the first-semester version
(personality notes, fortunes, love compatibility and the ASCII signs) instead
of retyping it. Run from the repo root after changing anything in legacy/:

    python tools/extract_legacy.py

What it changes on the way:
- the legacy files are Windows-1252; text is converted to plain UTF-8
- the leading "\\n*  " used for screen layout is removed
- two fortunes that were glued together by missing commas are split again
- a handful of mean-spirited fortunes are left out of the modern app
  (they stay in legacy/ untouched)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEGACY = ROOT / "legacy"
OUT = ROOT / "src" / "LegacyData.cpp"

SIGNS = ["aries", "taurus", "gemini", "cancer", "leo", "virgo",
         "libra", "scorpio", "saggitarius", "capricorn", "aquarius", "pisces"]
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')

# Fortunes from 2018 that don't belong in a friendly app.
DROP_FORTUNES = {
    "THE GREATEST DANGER COULD BE YOUR STUPIDITY.",
    "ITS A VERY *__UN*LUCKY WEEK IN WHICH TO BE TOOK DEAD.",
    "GET A LIFE!",
    "STAY AWAY FROM CARS TODAY.",
    "YOU'LL DIE IN A LOTTLE MORE THAN A MONTH.",
    "YOU'RE STUPID.",
    "HE WHO FARTS IN CHURCH, SITS IN HIS OWN PEW!",
}

# Fix the bytes that Windows-1252 maps to typographic characters, then keep ASCII.
SMART = {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
         "\u2013": "-", "\u2014": "-", "\u2026": "...", "\u00a0": " "}


def read(name):
    return (LEGACY / name).read_bytes().decode("cp1252", errors="replace")


def unescape(s):
    s = s.replace('\\"', '"').replace("\\\\", "\\").replace("\\n", "\n").replace("\\t", " ")
    s = "".join(SMART.get(ch, ch) for ch in s)
    s = s.replace("\ufffd", "'")
    return s


def strings_in(block):
    return [unescape(m) for m in STRING.findall(block)]


def clean_line(s):
    return re.sub(r"\s+", " ", s.replace("\n", " ").lstrip(" *").strip())


def cpp(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def extract_about(src):
    starts = [(m.start(), m.group(1)) for m in re.finditer(r"\nvoid (\w+)\(int x,int y,char \*a, char s\)", src)]
    about = {}
    for i, (pos, name) in enumerate(starts):
        body = src[pos: starts[i + 1][0] if i + 1 < len(starts) else len(src)]
        arr = re.search(r"char \*\w+\[\]=\{(.*?)\};", body, re.S)
        about[name] = [clean_line(s) for s in strings_in(arr.group(1)) if clean_line(s)]
    return about


def extract_ascii(fcn):
    """Replay the gotoxy()/printf() calls of asciiXXX() onto a small text grid."""
    art = {}
    for sign in SIGNS:
        body = re.search(r"void ascii" + sign + r"\(\)\s*\{(.*?)\n\s*\}", fcn, re.S).group(1)
        grid = {}
        for x, y, text in re.findall(r"gotoxy\((\d+),(\d+)\);\s*printf\(\"((?:[^\"\\]|\\.)*)\"", body):
            x, y = int(x), int(y)
            if y == 2:  # "Your horoscope sign is ..." line: the modern UI prints its own title
                continue
            text = unescape(text).replace("%c", "\\").split("\n")[0]
            row = grid.setdefault(y, {})
            for k, ch in enumerate(text):
                row[x + k] = ch
        lines = []
        for y in sorted(grid):
            row = grid[y]
            lines.append("".join(row.get(c, " ") for c in range(0, max(row) + 1)).rstrip())
        left = min(len(l) - len(l.lstrip()) for l in lines if l.strip())
        art[sign] = [l[left:] for l in lines]
    return art


def main():
    horo = read("horoscopes.h")
    fcn = read("fcn.h")

    about = extract_about(horo)
    love = [clean_line(s) for s in strings_in(re.search(r"char \*love\[\]=\{(.*?)\};", fcn, re.S).group(1))]
    raw_fortunes = strings_in(re.search(r"char \*fort\[\]=\{(.*?)\};", fcn, re.S).group(1))
    fortunes = []
    for f in raw_fortunes:
        # missing commas in the original merged two fortunes into one string
        for part in re.split(r"(?<=[.!?])(?=[A-Z])", clean_line(f)):
            part = part.strip()
            if part and part not in DROP_FORTUNES and part not in fortunes:
                fortunes.append(part)
    art = extract_ascii(fcn)

    assert len(about) == 12 and len(love) == 78, (len(about), len(love))

    out = ["// GENERATED by tools/extract_legacy.py from legacy/. Do not edit by hand.",
           "// Every text here was written for the original first-semester version.",
           '#include "LegacyData.hpp"', "", "namespace legacy {", ""]
    out.append("const std::vector<std::vector<std::string>> kAbout = {")
    for sign in SIGNS:
        out.append("    { // " + sign)
        out += ["        " + cpp(s) + "," for s in about[sign]]
        out.append("    },")
    out.append("};\n")
    out.append("const std::vector<std::string> kLove = {")
    out += ["    " + cpp(s) + "," for s in love]
    out.append("};\n")
    out.append("const std::vector<std::string> kFortunes = {")
    out += ["    " + cpp(s) + "," for s in fortunes]
    out.append("};\n")
    out.append("const std::vector<std::vector<std::string>> kArt = {")
    for sign in SIGNS:
        out.append("    { // " + sign)
        out += ["        " + cpp(s) + "," for s in art[sign]]
        out.append("    },")
    out.append("};\n")
    out.append("} // namespace legacy\n")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(map(len, about.values()))} personality notes, "
          f"{len(love)} love texts, {len(fortunes)} fortunes, 12 ASCII signs")


if __name__ == "__main__":
    main()
